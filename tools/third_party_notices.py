"""Writes THIRD-PARTY-NOTICES.txt: the licences of the third-party code the engine ships.

The vcpkg libraries' licences come from their installed copyright files (so configure first); the
vendored code's and fonts' from third-party/. Libraries used only to build or test (Catch2, stb, and
libspng, which libjpeg-turbo's TurboJPEG API needs but the engine doesn't link) aren't distributed, so
they're left out.

Usage: python tools/third_party_notices.py [--triplet x64-windows]
"""
import argparse
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent

# (name, licence, what the engine uses it for, licence source). A source is a vcpkg port name, or a
# path under the repository; a (path, start marker, end marker) tuple takes part of a file.
COMPONENTS = [
    ("brotli", "MIT", "WOFF2 font decompression", "brotli"),
    ("bzip2", "bzip2 licence (BSD-style)", "FreeType's compressed font support", "bzip2"),
    ("{fmt}", "MIT", "formatting, under spdlog", "fmt"),
    ("FreeType", "FreeType License (FTL), chosen from FTL or GPL-2.0", "font rasterising", None),
    ("HarfBuzz", "MIT (\"Old MIT\" and MIT)", "text shaping", "harfbuzz"),
    ("ICU", "Unicode License v3 (ICU)", "Unicode properties, bidi, breaking, locales", "icu"),
    ("Little CMS", "MIT", "colour profiles", "lcms"),
    ("libjpeg-turbo", "IJG licence and BSD-3-Clause", "JPEG", "libjpeg-turbo"),
    ("libpng", "PNG Reference Library License v2", "PNG", "libpng"),
    ("libwebp", "BSD-3-Clause", "WebP", "libwebp"),
    ("libxml2", "MIT", "XML", "libxml2"),
    ("RapidJSON", "MIT", "JSON", "rapidjson"),
    ("RapidXML", "MIT, chosen from Boost Software License 1.0 or MIT", "XML", "rapidxml"),
    ("rapidhash", "BSD-2-Clause", "hashing", "rapidhash"),
    ("spdlog", "MIT", "logging", "spdlog"),
    ("unordered_dense", "MIT", "hash maps and sets", "unordered-dense"),
    ("WOFF2", "MIT", "WOFF2 fonts", "woff2"),
    ("zlib", "zlib licence", "compression", "zlib"),
    ("LLVM (SmallVector, MemAlloc)", "Apache-2.0 WITH LLVM-exception", "small vectors",
     "third-party/llvm/LICENSE.TXT"),
    ("Liberation Fonts", "SIL Open Font License 1.1", "bundled font", "third-party/liberation-fonts/LICENSE"),
    ("Noto Sans Arabic", "SIL Open Font License 1.1", "bundled font", "third-party/noto-sans-arabic/OFL.txt"),
    ("STIX Two", "SIL Open Font License 1.1", "bundled font", "third-party/stix-two-fonts/OFL.txt"),
]

RULE = "=" * 78


def read(path):
    return path.read_text(encoding="utf-8-sig", errors="replace").replace("\r\n", "\n").strip("\n")


def licence_text(name, source, share):
    if name == "FreeType":
        # The port's copyright file holds the licence choice, the FTL and the GPL: keep the FTL.
        text = read(share / "freetype" / "copyright")
        return text[text.index("FTL.TXT:") + len("FTL.TXT:"):text.index("GPLv2.TXT:")].strip("\n")
    if source.startswith("third-party/"):
        return read(ROOT / source)
    return read(share / source / "copyright")


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--triplet", default="x64-windows")
    args = parser.parse_args()
    share = ROOT / "build" / "vcpkg_installed" / args.triplet / "share"

    out = [
        "THIRD-PARTY NOTICES",
        "",
        "KrystalEngine includes or links the third-party software below. Each is used under the licence",
        "given, whose full text follows. Generated by tools/third_party_notices.py.",
        "",
    ]
    for name, licence, use, _ in COMPONENTS:
        out.append(f"- {name}: {licence} ({use})")
    for name, licence, _, source in COMPONENTS:
        out += ["", RULE, f"{name}: {licence}", RULE, "", licence_text(name, source, share)]

    path = ROOT / "THIRD-PARTY-NOTICES.txt"
    path.write_text("﻿" + "\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"Wrote {path.relative_to(ROOT)} ({len(COMPONENTS)} components)")


if __name__ == "__main__":
    main()
