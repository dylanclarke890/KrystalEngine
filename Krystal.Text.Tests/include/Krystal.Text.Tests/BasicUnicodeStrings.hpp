  template <typename Container>
  inline Span<const byte> RangeToBytes(Container &c)
  {
    return std::as_bytes(Span<remove_pointer_t<decltype(c.data())>>(c.data(), c.size()));
  }

  template <typename Container>
  inline Span<const byte> as_writeable_bytes(Container &c)
  {
    return std::as_writable_bytes(Span<remove_pointer_t<decltype(c.data())>>(c.data(), c.size()));
  }

  template <typename Char>
  constexpr auto make_basic_source_character_set_reverse_storage_for() noexcept
  {
    auto make_array = []()
    {
      if constexpr (SameType<Char, char>)
      {
        const auto &bscs =
          "\f\v\t "
          "\nabcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_{}[]#()<>%:;.?*+-/"
          "^&|~!=,\\\"'\0";
        std::array<Char, 97> arr;
        std::copy(std::begin(bscs), std::end(bscs) - 1, arr.begin());
        return arr;
      }
      else if constexpr (SameType<Char, wchar_t>)
      {
        const auto &bscs =
          L"\f\v\t "
          "\nabcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_{}[]#()<>%:;.?*+-/"
          "^&|~!=,\\\"'\0";
        std::array<Char, 97> arr;
        std::copy(std::begin(bscs), std::end(bscs) - 1, arr.begin());
        return arr;
      }
      else if constexpr (SameType<Char, char8_t>)
      {
        const auto &bscs =
          u8"\f\v\t "
          "\nabcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_{}[]#()<>%:;.?*+-/"
          "^&|~!=,\\\"'\0";
        std::array<Char, 97> arr;
        std::copy(std::begin(bscs), std::end(bscs) - 1, arr.begin());
        return arr;
      }
      else if constexpr (SameType<Char, uchar8>)
      {
        const auto &bscs =
          u8"\f\v\t "
          "\nabcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_{}[]#()<>%:;.?*+-/"
          "^&|~!=,\\\"'\0";
        std::array<Char, 97> arr;
        std::copy(std::begin(bscs), std::end(bscs) - 1, arr.begin());
        return arr;
      }
      else if constexpr (SameType<Char, char16_t>)
      {
        const auto &bscs =
          u"\f\v\t "
          "\nabcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_{}[]#()<>%:;.?*+-/"
          "^&|~!=,\\\"'\0";
        std::array<Char, 97> arr;
        std::copy(std::begin(bscs), std::end(bscs) - 1, arr.begin());
        return arr;
      }
      else if constexpr (SameType<Char, char32_t>)
      {
        const auto &bscs =
          U"\f\v\t "
          "\nabcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_{}[]#()<>%:;.?*+-/"
          "^&|~!=,\\\"'\0";
        std::array<Char, 97> arr;
        std::copy(std::begin(bscs), std::end(bscs) - 1, arr.begin());
        return arr;
      }
      else
      {
        static_assert(DependentFalse<Char>, "no");
      }
    };
    auto arr = make_array();
    if constexpr (sizeof(Char) > 1)
    {
      unsigned char *aliased_data = reinterpret_cast<unsigned char *>(arr.data());
      unsigned char *aliased_data_last = reinterpret_cast<unsigned char *>(arr.data() + arr.size());
      for (; aliased_data != aliased_data_last; aliased_data += sizeof(Char))
      {
        std::reverse(aliased_data, aliased_data + sizeof(Char));
      }
    }
    return arr;
  }

  template <typename Char>
  const auto &basic_source_character_set_reverse_storage() noexcept
  {
    static const auto arr = make_basic_source_character_set_reverse_storage_for<Char>();
    return arr;
  }

