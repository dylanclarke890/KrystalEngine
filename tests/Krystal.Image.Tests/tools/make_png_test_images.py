"""Generates include/Krystal.Image.Tests/PNGImages.hpp: PNGs that exercise the PNG decoder's harder paths.

- InterlacedPNG: 9x9 RGB, Adam7 interlaced, pixel (x, y) coloured (x * 28, y * 28, 128).
- PalettePNG: 3x1, a palette of red, green and blue with tRNS making blue transparent.
- GrayAlpha16PNG: 2x1, 16-bit grey and alpha: opaque white, then transparent.
- BlendAPNG: a 4x4 RGBA animation, played twice, whose default image (white) isn't part of it. Its frames:
  red everywhere; a 2x2 at (0, 0) blended over it, green on the left and transparent on the right, then
  restored to the background; an opaque blue 2x2 at (2, 2), then restored to the previous frame; and a
  transparent pixel replacing (3, 0).
- InterlacedBlendAPNG: BlendAPNG, with every frame Adam7 interlaced.
- BrokenAPNG: BlendAPNG with the third frame's data out of sequence, which ends the animation there.

Usage: python make_png_test_images.py
"""

import pathlib
import struct
import zlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUTPUT = ROOT / 'include' / 'Krystal.Image.Tests' / 'PNGImages.hpp'

SIGNATURE = b'\x89PNG\r\n\x1a\n'
ADAM7 = [(0, 0, 8, 8), (4, 0, 8, 8), (0, 4, 4, 8), (2, 0, 4, 4), (0, 2, 2, 4), (1, 0, 2, 2), (0, 1, 1, 2)]
DISPOSE_NONE, DISPOSE_BACKGROUND, DISPOSE_PREVIOUS = 0, 1, 2
BLEND_SOURCE, BLEND_OVER = 0, 1


def chunk(kind, data):
    return struct.pack('>I', len(data)) + kind + data + struct.pack('>I', zlib.crc32(kind + data))


def header(width, height, bit_depth, color_type, interlaced=False):
    return chunk(b'IHDR', struct.pack('>IIBBBBB', width, height, bit_depth, color_type, 0, 0, int(interlaced)))


def scanlines(rows, interlaced):
    """The image data of rows of pixels (each a bytes object per pixel), filtered with no filter."""
    if not interlaced:
        return b''.join(b'\0' + b''.join(row) for row in rows)
    height, width = len(rows), len(rows[0])
    out = b''
    for x0, y0, dx, dy in ADAM7:
        pass_rows = [b''.join(rows[y][x] for x in range(x0, width, dx)) for y in range(y0, height, dy)]
        out += b''.join(b'\0' + row for row in pass_rows if row)
    return out


def image_data(rows, interlaced=False):
    return zlib.compress(scanlines(rows, interlaced))


def still(ihdr, rows, interlaced=False, extra=b''):
    return SIGNATURE + ihdr + extra + chunk(b'IDAT', image_data(rows, interlaced)) + chunk(b'IEND', b'')


def blend_apng(interlaced=False, break_sequence=False):
    red, green, blue, white = b'\xff\0\0\xff', b'\0\xff\0\xff', b'\0\0\xff\xff', b'\xff\xff\xff\xff'
    clear = b'\0\0\0\0'
    frames = [
        (0, 0, [[red] * 4] * 4, DISPOSE_NONE, BLEND_SOURCE),
        (0, 0, [[green, clear]] * 2, DISPOSE_BACKGROUND, BLEND_OVER),
        (2, 2, [[blue] * 2] * 2, DISPOSE_PREVIOUS, BLEND_SOURCE),
        (3, 0, [[clear]], DISPOSE_NONE, BLEND_SOURCE),
    ]
    out = SIGNATURE + header(4, 4, 8, 6, interlaced)
    out += chunk(b'acTL', struct.pack('>II', len(frames), 2))
    out += chunk(b'IDAT', image_data([[white] * 4] * 4, interlaced))
    sequence = 0
    for index, (x, y, rows, dispose, blend) in enumerate(frames):
        width, height = len(rows[0]), len(rows)
        out += chunk(b'fcTL', struct.pack('>IIIIIHHBB', sequence, width, height, x, y, 1, 10, dispose, blend))
        sequence += 1
        number = sequence + (1 if break_sequence and index == 2 else 0)
        out += chunk(b'fdAT', struct.pack('>I', number) + image_data(rows, interlaced))
        sequence += 1
    return out + chunk(b'IEND', b'')


def cpp_array(name, data):
    lines = [f'  constexpr inline uint8 {name}Bytes[] = {{']
    for start in range(0, len(data), 17):
        lines.append('    ' + ' '.join(f'0x{b:02X},' for b in data[start:start + 17]))
    lines += ['  };', f'  constexpr inline Span<const uint8> {name} {{{name}Bytes}};']
    return '\n'.join(lines)


def main():
    gradient = [[bytes((x * 28, y * 28, 128)) for x in range(9)] for y in range(9)]
    interlaced = still(header(9, 9, 8, 2, True), gradient, interlaced=True)

    palette = chunk(b'PLTE', bytes((255, 0, 0, 0, 255, 0, 0, 0, 255))) + chunk(b'tRNS', bytes((255, 255, 0)))
    palette_png = still(header(3, 1, 8, 3), [[b'\0', b'\1', b'\2']], extra=palette)

    gray_alpha = still(header(2, 1, 16, 4), [[b'\xff\xff\xff\xff', b'\0\0\0\0']])

    text = '\n'.join([
        '﻿#pragma once',
        '',
        '#include "Krystal.Core/Containers/Span.hpp"',
        '#include "Krystal.Core/Numeric.hpp"',
        '',
        '// Generated by tools/make_png_test_images.py, which describes each image.',
        'namespace krys::img::tests::images',
        '{',
        cpp_array('InterlacedPNG', interlaced),
        cpp_array('PalettePNG', palette_png),
        cpp_array('GrayAlpha16PNG', gray_alpha),
        cpp_array('BlendAPNG', blend_apng()),
        cpp_array('InterlacedBlendAPNG', blend_apng(interlaced=True)),
        cpp_array('BrokenAPNG', blend_apng(break_sequence=True)),
        '}',
        '',
    ])
    OUTPUT.write_text(text, encoding='utf-8', newline='\n')
    print(f'Wrote {OUTPUT.relative_to(ROOT.parent)}')


if __name__ == '__main__':
    main()
