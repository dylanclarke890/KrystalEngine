"""Generates include/Krystal.Image.Tests/JPEGImages.hpp with TurboJPEG (from vcpkg, so configure first).

Writes a progressive JPEG of the test JPEG's picture (16x8, red on the left half and blue on the right), in
several scans, and a CMYK JPEG (Adobe's inverted CMYK) of the same picture, with no ICC profile.

Usage: python make_jpeg_test_images.py [--triplet x64-windows]
"""

import argparse
import ctypes
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
REPO = ROOT.parent
OUTPUT = ROOT / 'include' / 'Krystal.Image.Tests' / 'JPEGImages.hpp'

WIDTH, HEIGHT = 16, 8


def enumerators(header, name):
    """The values of the named C enum's enumerators, which count up from 0."""
    body = re.search(r'enum\s+' + name + r'\s*\{(.*?)\}', header, re.S).group(1)
    body = re.sub(r'/\*.*?\*/', '', body, flags=re.S)
    names = [entry.split('=')[0].strip() for entry in body.split(',') if entry.strip()]
    return {enumerator: value for value, enumerator in enumerate(names)}


def picture(channels):
    """The test picture's pixels, a row at a time, in the given channel values for red and blue."""
    red, blue = channels
    return bytes(b for y in range(HEIGHT) for x in range(WIDTH) for b in (red if x < WIDTH // 2 else blue))


class TurboJPEG:
    def __init__(self, triplet):
        installed = REPO / 'build' / 'vcpkg_installed' / triplet
        header = (installed / 'include' / 'turbojpeg.h').read_text(encoding='utf-8', errors='replace')
        self.init = enumerators(header, 'TJINIT')
        self.pf = enumerators(header, 'TJPF')
        self.cs = enumerators(header, 'TJCS')
        self.samp = enumerators(header, 'TJSAMP')
        self.param = enumerators(header, 'TJPARAM')
        self.lib = ctypes.CDLL(str(installed / 'bin' / 'turbojpeg.dll'))
        self.lib.tj3Init.restype = ctypes.c_void_p
        self.lib.tj3Init.argtypes = [ctypes.c_int]
        self.lib.tj3Set.argtypes = [ctypes.c_void_p, ctypes.c_int, ctypes.c_int]
        self.lib.tj3Compress8.argtypes = [ctypes.c_void_p, ctypes.c_char_p, ctypes.c_int, ctypes.c_int, ctypes.c_int,
                                          ctypes.c_int, ctypes.POINTER(ctypes.c_void_p),
                                          ctypes.POINTER(ctypes.c_size_t)]
        self.lib.tj3Free.argtypes = [ctypes.c_void_p]
        self.lib.tj3Destroy.argtypes = [ctypes.c_void_p]

    def compress(self, pixels, pixel_format, settings):
        handle = self.lib.tj3Init(self.init['TJINIT_COMPRESS'])
        try:
            for param, value in settings.items():
                assert self.lib.tj3Set(handle, self.param[param], value) == 0, param
            channels = len(pixels) // (WIDTH * HEIGHT)
            buffer, size = ctypes.c_void_p(), ctypes.c_size_t()
            result = self.lib.tj3Compress8(handle, pixels, WIDTH, WIDTH * channels, HEIGHT, self.pf[pixel_format],
                                           ctypes.byref(buffer), ctypes.byref(size))
            assert result == 0, 'tj3Compress8 failed'
            data = ctypes.string_at(buffer, size.value)
            self.lib.tj3Free(buffer)
            return data
        finally:
            self.lib.tj3Destroy(handle)


def cpp_array(name, data):
    lines = [f'  constexpr inline uint8 {name}Bytes[] = {{']
    for start in range(0, len(data), 17):
        lines.append('    ' + ' '.join(f'0x{b:02X},' for b in data[start:start + 17]))
    lines += ['  };', f'  constexpr inline Span<const uint8> {name} {{{name}Bytes}};']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--triplet', default='x64-windows')
    args = parser.parse_args()
    tj = TurboJPEG(args.triplet)

    rgb = picture(((255, 0, 0), (0, 0, 255)))
    progressive = tj.compress(rgb, 'TJPF_RGB', {
        'TJPARAM_QUALITY': 95, 'TJPARAM_SUBSAMP': tj.samp['TJSAMP_444'], 'TJPARAM_PROGRESSIVE': 1})
    # TurboJPEG stores CMYK values as they're given, but decoders read them as Adobe's inverted CMYK (255 for no
    # ink), so they're inverted here. Red is magenta and yellow ink; blue is cyan and magenta.
    def inverted(ink):
        return tuple(255 - amount for amount in ink)

    cmyk = picture((inverted((0, 255, 255, 0)), inverted((255, 255, 0, 0))))
    cmyk_jpeg = tj.compress(cmyk, 'TJPF_CMYK', {
        'TJPARAM_QUALITY': 95, 'TJPARAM_SUBSAMP': tj.samp['TJSAMP_444'], 'TJPARAM_COLORSPACE': tj.cs['TJCS_YCCK']})

    text = '\n'.join([
        '﻿#pragma once',
        '',
        '#include "Krystal.Core/Containers/Span.hpp"',
        '#include "Krystal.Core/Numeric.hpp"',
        '',
        '// Generated by tools/make_jpeg_test_images.py with TurboJPEG: the test JPEG\'s picture (16x8, red on the',
        '// left half and blue on the right) as a progressive JPEG, and as a YCCK (inverted CMYK) JPEG with no profile.',
        'namespace krys::img::tests::images',
        '{',
        cpp_array('ProgressiveJPEG', progressive),
        cpp_array('CMYKJPEG', cmyk_jpeg),
        '}',
        '',
    ])
    OUTPUT.write_text(text, encoding='utf-8', newline='\n')
    print(f'Wrote {OUTPUT.relative_to(REPO)} ({len(progressive)} and {len(cmyk_jpeg)} bytes)')


if __name__ == '__main__':
    main()
