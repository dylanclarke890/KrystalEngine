  const NamedColor *FindColor(std::u8string_view name) noexcept
  {
    auto it = std::ranges::lower_bound(NamedColors, name, {}, &NamedColor::Name);
    if (it == NamedColors.end() || it->Name != name)
    {
      return nullptr;
    }
    return &*it;
  }
