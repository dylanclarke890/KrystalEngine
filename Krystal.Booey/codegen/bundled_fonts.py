"""Embeds the bundled font files in Krystal.Booey as byte arrays (Graphics/BundledFonts.hpp, .cpp)."""

import argparse
import pathlib

FILE_NAME = "BundledFonts"

# (C++ function name, font file under the fonts directory)
FONTS = [
    ("LiberationSansRegular", "liberation-fonts/LiberationSans-Regular.ttf"),
    ("STIXTwoMathRegular", "stix-two-fonts/STIXTwoMath-Regular.otf"),
]

BYTES_PER_LINE = 24


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Embed the bundled fonts.")
    parser.add_argument("--fonts-dir", required=True, help="Directory containing the font directories (third-party/).")
    parser.add_argument("--output-headers-dir", required=True, help="Output directory for the generated header.")
    parser.add_argument("--output-sources-dir", required=True, help="Output directory for the generated source.")
    return parser.parse_args()


def write_if_changed(path: pathlib.Path, contents: str) -> None:
    data = "﻿" + contents
    if path.exists() and path.read_text(encoding="utf-8") == data:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(data, encoding="utf-8", newline="\n")


def generate_header() -> str:
    lines = [
        "// Generated by codegen/bundled_fonts.py. Do not edit.",
        "#pragma once",
        "",
        '#include "Krystal.Core/Attributes.hpp"',
        '#include "Krystal.Core/Numeric.hpp"',
        '#include "Krystal.Core/Types/Span.hpp"',
        "",
        "namespace krys::boo",
        "{",
    ]
    for function_name, file_name in FONTS:
        lines.append(f"  /// @brief The contents of `{pathlib.PurePosixPath(file_name).name}`.")
        lines.append(f"  KRYS_NODISCARD Span<const byte> Bundled{function_name}() noexcept;")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def generate_source(fonts_dir: pathlib.Path) -> str:
    lines = [
        "// Generated by codegen/bundled_fonts.py. Do not edit.",
        f'#include "Krystal.Booey/Graphics/{FILE_NAME}.hpp"',
        "",
        "namespace krys::boo",
        "{",
    ]
    for function_name, file_name in FONTS:
        data = (fonts_dir / file_name).read_bytes()
        array_name = f"{function_name}Data"
        lines.append(f"  alignas(16) static constexpr unsigned char {array_name}[] = {{")
        for offset in range(0, len(data), BYTES_PER_LINE):
            chunk = data[offset : offset + BYTES_PER_LINE]
            lines.append("    " + ",".join(f"0x{value:02x}" for value in chunk) + ",")
        lines.append("  };")
        lines.append("")
        lines.append(f"  Span<const byte> Bundled{function_name}() noexcept")
        lines.append("  {")
        lines.append(f"    return Span<const byte>(reinterpret_cast<const byte *>({array_name}), sizeof({array_name}));")
        lines.append("  }")
        lines.append("")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    args = parse_args()
    fonts_dir = pathlib.Path(args.fonts_dir)
    write_if_changed(pathlib.Path(args.output_headers_dir) / "Krystal.Booey" / "Graphics" / f"{FILE_NAME}.hpp", generate_header())
    write_if_changed(pathlib.Path(args.output_sources_dir) / "Graphics" / f"{FILE_NAME}.cpp", generate_source(fonts_dir))


if __name__ == "__main__":
    main()
